-- Blossom Petals customer loyalty program.
-- Earn 1 petal for each 100 DA actually collected. Redeem 100 petals for 500 DA.

CREATE TABLE IF NOT EXISTS public.customer_loyalty_transactions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id integer NOT NULL REFERENCES public.customers(customer_id) ON DELETE CASCADE,
  order_id uuid REFERENCES public.orders(id) ON DELETE SET NULL,
  request_id uuid UNIQUE,
  transaction_type text NOT NULL CHECK (transaction_type IN ('earn', 'redeem', 'adjustment')),
  points_delta integer NOT NULL CHECK (points_delta <> 0),
  note text NOT NULL DEFAULT '',
  created_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS customer_loyalty_transactions_customer_created_idx
  ON public.customer_loyalty_transactions(customer_id, created_at DESC);
CREATE INDEX IF NOT EXISTS customer_loyalty_transactions_order_idx
  ON public.customer_loyalty_transactions(order_id) WHERE order_id IS NOT NULL;

ALTER TABLE public.customer_loyalty_transactions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.customer_loyalty_transactions FROM PUBLIC, anon, authenticated;
GRANT SELECT ON TABLE public.customer_loyalty_transactions TO authenticated;

DROP POLICY IF EXISTS customer_loyalty_transactions_staff_read ON public.customer_loyalty_transactions;
CREATE POLICY customer_loyalty_transactions_staff_read
  ON public.customer_loyalty_transactions FOR SELECT TO authenticated
  USING (EXISTS (
    SELECT 1 FROM public.profiles p
    WHERE p.id = auth.uid()
      AND coalesce(p.is_active, false)
      AND p.role IN ('owner', 'manager', 'florist', 'cashier')
  ));

CREATE OR REPLACE FUNCTION public.blossom_loyalty_points_for_order(
  p_customer_id integer,
  p_status text,
  p_total numeric,
  p_paid numeric
)
RETURNS integer
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT CASE
    WHEN p_customer_id IS NULL OR p_status = 'cancelled' THEN 0
    ELSE floor(greatest(0, least(coalesce(p_total, 0), coalesce(p_paid, 0))) / 100)::integer
  END;
$$;

CREATE OR REPLACE FUNCTION public.blossom_sync_order_loyalty_points()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_old_points integer := 0;
  v_new_points integer := 0;
BEGIN
  IF TG_OP <> 'INSERT' THEN
    v_old_points := public.blossom_loyalty_points_for_order(
      OLD.customer_id, OLD.status, OLD.total_amount, OLD.amount_paid
    );
  END IF;
  IF TG_OP <> 'DELETE' THEN
    v_new_points := public.blossom_loyalty_points_for_order(
      NEW.customer_id, NEW.status, NEW.total_amount, NEW.amount_paid
    );
  END IF;

  IF TG_OP = 'DELETE' THEN
    IF OLD.customer_id IS NOT NULL AND v_old_points > 0 THEN
      INSERT INTO public.customer_loyalty_transactions
        (customer_id, transaction_type, points_delta, note, created_by)
      VALUES (OLD.customer_id, 'adjustment', -v_old_points,
        'Earned petals reversed because the order was deleted', auth.uid());
    END IF;
    RETURN OLD;
  ELSIF TG_OP = 'UPDATE' AND OLD.customer_id IS NOT DISTINCT FROM NEW.customer_id THEN
    IF v_new_points <> v_old_points AND NEW.customer_id IS NOT NULL THEN
      INSERT INTO public.customer_loyalty_transactions
        (customer_id, order_id, transaction_type, points_delta, note, created_by)
      VALUES (
        NEW.customer_id, NEW.id,
        CASE WHEN v_new_points > v_old_points THEN 'earn' ELSE 'adjustment' END,
        v_new_points - v_old_points,
        CASE WHEN v_new_points > v_old_points
          THEN 'Petals earned from collected order payment'
          ELSE 'Earned petals adjusted after order change, cancellation, or refund'
        END,
        auth.uid()
      );
    END IF;
    RETURN NEW;
  END IF;

  IF TG_OP = 'UPDATE' AND OLD.customer_id IS NOT NULL AND v_old_points > 0 THEN
    INSERT INTO public.customer_loyalty_transactions
      (customer_id, order_id, transaction_type, points_delta, note, created_by)
    VALUES (OLD.customer_id, OLD.id, 'adjustment', -v_old_points,
      'Earned petals moved with the order customer', auth.uid());
  END IF;
  IF NEW.customer_id IS NOT NULL AND v_new_points > 0 THEN
    INSERT INTO public.customer_loyalty_transactions
      (customer_id, order_id, transaction_type, points_delta, note, created_by)
    VALUES (NEW.customer_id, NEW.id, 'earn', v_new_points,
      'Petals earned from collected order payment', auth.uid());
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS orders_sync_loyalty_points ON public.orders;
CREATE TRIGGER orders_sync_loyalty_points
  AFTER INSERT OR UPDATE OR DELETE
  ON public.orders
  FOR EACH ROW EXECUTE FUNCTION public.blossom_sync_order_loyalty_points();
REVOKE ALL ON FUNCTION public.blossom_sync_order_loyalty_points() FROM PUBLIC, anon, authenticated;

-- Create an order and redeem petals in the same transaction. The existing
-- order RPC remains responsible for stock, payment, and cash-register writes.
CREATE OR REPLACE FUNCTION public.blossom_create_loyalty_order(
  p_order jsonb,
  p_items jsonb,
  p_request_id uuid,
  p_points_to_redeem integer
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_user_id uuid := auth.uid();
  v_customer_id integer;
  v_balance bigint;
  v_discount integer;
  v_order jsonb;
  v_order_id uuid;
  v_order_payload jsonb;
  v_existing boolean;
  v_base_total numeric;
  v_role text;
  v_active boolean;
BEGIN
  IF v_user_id IS NULL THEN RAISE EXCEPTION 'must be signed in'; END IF;
  SELECT role, is_active INTO v_role, v_active FROM public.profiles WHERE id = v_user_id;
  IF NOT coalesce(v_active, false) OR coalesce(v_role, '') NOT IN ('owner', 'manager', 'florist', 'cashier') THEN
    RAISE EXCEPTION 'role cannot create orders';
  END IF;
  IF p_request_id IS NULL OR p_points_to_redeem IS NULL OR p_points_to_redeem < 100
     OR p_points_to_redeem % 100 <> 0 THEN
    RAISE EXCEPTION 'redeem petals in multiples of 100';
  END IF;
  IF jsonb_typeof(p_order) IS DISTINCT FROM 'object'
     OR jsonb_typeof(p_items) IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION 'invalid order payload';
  END IF;

  v_customer_id := nullif(p_order->>'customer_id', '')::integer;
  IF v_customer_id IS NULL THEN RAISE EXCEPTION 'a customer profile is required to redeem petals'; END IF;
  v_discount := p_points_to_redeem * 5;
  SELECT coalesce(sum((item->>'quantity')::numeric * (item->>'unit_price')::numeric), 0)
       + coalesce(nullif(p_order->>'tax_amount', '')::numeric, 0)
       + coalesce(nullif(p_order->>'price_adjustment', '')::numeric, 0)
    INTO v_base_total
  FROM jsonb_array_elements(p_items) AS lines(item);
  IF v_discount > greatest(0, v_base_total) THEN
    RAISE EXCEPTION 'petal reward is greater than the order total';
  END IF;
  v_order_payload := jsonb_set(
    p_order,
    '{price_adjustment}',
    to_jsonb(coalesce(nullif(p_order->>'price_adjustment', '')::integer, 0) - v_discount),
    true
  );

  -- Serialize redemptions for this customer and make retries idempotent.
  PERFORM 1 FROM public.customers WHERE customer_id = v_customer_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'customer not found'; END IF;
  SELECT EXISTS (
    SELECT 1 FROM public.customer_loyalty_transactions
    WHERE request_id = p_request_id AND transaction_type = 'redeem'
  ) INTO v_existing;

  IF NOT v_existing THEN
    SELECT coalesce(sum(points_delta), 0) INTO v_balance
    FROM public.customer_loyalty_transactions WHERE customer_id = v_customer_id;
    IF v_balance < p_points_to_redeem THEN
      RAISE EXCEPTION 'not enough petals; this customer currently has %', greatest(v_balance, 0);
    END IF;
  END IF;

  v_order := public.blossom_create_order(v_order_payload, p_items, p_request_id);
  v_order_id := nullif(v_order->'order'->>'id', '')::uuid;
  IF v_order_id IS NULL THEN RAISE EXCEPTION 'order creation returned no order id'; END IF;

  IF NOT v_existing THEN
    INSERT INTO public.customer_loyalty_transactions
      (customer_id, order_id, request_id, transaction_type, points_delta, note, created_by)
    VALUES (
      v_customer_id, v_order_id, p_request_id, 'redeem', -p_points_to_redeem,
      format('Redeemed %s petals for %s DA off Order #%s', p_points_to_redeem, v_discount, v_order->'order'->>'order_number'),
      v_user_id
    );
  END IF;

  RETURN v_order;
END;
$$;

REVOKE ALL ON FUNCTION public.blossom_create_loyalty_order(jsonb, jsonb, uuid, integer) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.blossom_create_loyalty_order(jsonb, jsonb, uuid, integer) TO authenticated;

CREATE OR REPLACE FUNCTION public.blossom_loyalty_dashboard_summary()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_user_id uuid := auth.uid();
  v_role text;
  v_active boolean;
  v_summary jsonb;
BEGIN
  IF v_user_id IS NULL THEN RAISE EXCEPTION 'must be signed in'; END IF;
  SELECT role, is_active INTO v_role, v_active FROM public.profiles WHERE id = v_user_id;
  IF NOT coalesce(v_active, false) OR coalesce(v_role, '') NOT IN ('owner', 'manager', 'florist', 'cashier') THEN
    RAISE EXCEPTION 'role cannot view loyalty program';
  END IF;

  WITH customer_totals AS (
    SELECT c.customer_id, c.full_name, c.phone,
      coalesce(sum(CASE WHEN t.transaction_type = 'earn' THEN t.points_delta ELSE 0 END), 0)::integer AS earned,
      coalesce(sum(CASE WHEN t.transaction_type = 'redeem' THEN -t.points_delta ELSE 0 END), 0)::integer AS redeemed,
      coalesce(sum(t.points_delta), 0)::integer AS balance
    FROM public.customers c
    LEFT JOIN public.customer_loyalty_transactions t ON t.customer_id = c.customer_id
    GROUP BY c.customer_id, c.full_name, c.phone
  )
  SELECT jsonb_build_object(
    'total_earned', coalesce(sum(earned), 0),
    'total_redeemed', coalesce(sum(redeemed), 0),
    'available_points', coalesce(sum(greatest(0, balance)), 0),
    'active_customers', count(*) FILTER (WHERE earned > 0),
    'top_customers', coalesce((
      SELECT jsonb_agg(jsonb_build_object(
        'customer_id', ranked.customer_id,
        'full_name', ranked.full_name,
        'phone', ranked.phone,
        'earned', ranked.earned,
        'balance', ranked.balance,
        'available_rewards', greatest(0, ranked.balance) / 100
      ) ORDER BY ranked.balance DESC, ranked.earned DESC)
      FROM (
        SELECT customer_id, full_name, phone, earned, balance
        FROM customer_totals
        WHERE balance > 0
        ORDER BY balance DESC, earned DESC, full_name ASC
        LIMIT 5
      ) ranked
    ), '[]'::jsonb)
  ) INTO v_summary
  FROM customer_totals;

  RETURN v_summary;
END;
$$;

REVOKE ALL ON FUNCTION public.blossom_loyalty_dashboard_summary() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.blossom_loyalty_dashboard_summary() TO authenticated;

