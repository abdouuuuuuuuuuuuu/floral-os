-- Structured delivery attempts.
--
-- Reconstructed on 2026-10-30 from the live schema: the original file in this
-- repository had been truncated to a single byte. Every statement is
-- idempotent so it is safe to run against the live project, where these
-- objects already exist.
--
-- Missing from the export: the body of blossom_capture_delivery_attempt_event()
-- (the order activity timeline hook). The trigger below is attached only when
-- that function already exists.

CREATE TABLE IF NOT EXISTS public.delivery_attempts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id uuid NOT NULL,
  order_id uuid NOT NULL,
  order_number text NOT NULL,
  reason text NOT NULL,
  resolution text NOT NULL,
  attempted_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  attempted_by uuid,
  actor_name text NOT NULL,
  previous_delivery_date date,
  rescheduled_delivery_date date
);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'delivery_attempts_request_id_key') THEN
    ALTER TABLE public.delivery_attempts ADD CONSTRAINT delivery_attempts_request_id_key UNIQUE (request_id);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'delivery_attempts_reason_check') THEN
    ALTER TABLE public.delivery_attempts ADD CONSTRAINT delivery_attempts_reason_check
      CHECK (char_length(btrim(reason)) BETWEEN 1 AND 200);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'delivery_attempts_resolution_check') THEN
    ALTER TABLE public.delivery_attempts ADD CONSTRAINT delivery_attempts_resolution_check
      CHECK (resolution = ANY (ARRAY['returned_to_shop', 'rescheduled']::text[]));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'delivery_attempts_check') THEN
    ALTER TABLE public.delivery_attempts ADD CONSTRAINT delivery_attempts_check
      CHECK ((resolution = 'rescheduled') = (rescheduled_delivery_date IS NOT NULL));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'delivery_attempts_attempted_by_fkey') THEN
    ALTER TABLE public.delivery_attempts ADD CONSTRAINT delivery_attempts_attempted_by_fkey
      FOREIGN KEY (attempted_by) REFERENCES auth.users(id) ON DELETE SET NULL;
  END IF;
END;
$$;

CREATE INDEX IF NOT EXISTS delivery_attempts_order_time_idx
  ON public.delivery_attempts (order_id, attempted_at DESC, id DESC);

ALTER TABLE public.delivery_attempts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.delivery_attempts FROM PUBLIC, anon;
REVOKE INSERT, UPDATE, DELETE ON TABLE public.delivery_attempts FROM authenticated;
GRANT SELECT ON TABLE public.delivery_attempts TO authenticated;

DROP POLICY IF EXISTS delivery_attempts_select_authorized ON public.delivery_attempts;
CREATE POLICY delivery_attempts_select_authorized
  ON public.delivery_attempts
  FOR SELECT TO authenticated
  USING (
    public.blossom_active_role() = ANY (ARRAY['owner', 'manager', 'florist', 'cashier', 'delivery']::text[])
    AND EXISTS (
      SELECT 1 FROM public.orders o
      WHERE o.id = delivery_attempts.order_id
        AND (o.deleted_at IS NULL OR public.blossom_active_role() = 'owner')
    )
  );

DO $$
BEGIN
  IF to_regprocedure('public.blossom_capture_delivery_attempt_event()') IS NOT NULL THEN
    DROP TRIGGER IF EXISTS delivery_attempts_capture_activity ON public.delivery_attempts;
    CREATE TRIGGER delivery_attempts_capture_activity
      AFTER INSERT ON public.delivery_attempts
      FOR EACH ROW EXECUTE FUNCTION public.blossom_capture_delivery_attempt_event();
  END IF;
END;
$$;

-- Records a failed delivery as one attempt row, then returns the order to the
-- shop or reschedules it. Retries with the same request id are idempotent.
CREATE OR REPLACE FUNCTION public.record_delivery_outcome(
  p_order_id uuid,
  p_reason text,
  p_actor text DEFAULT NULL,
  p_new_date date DEFAULT NULL,
  p_request_id uuid DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_user_id uuid := auth.uid();
  v_role text;
  v_active boolean;
  v_actor_name text;
  v_order public.orders%ROWTYPE;
  v_old_order jsonb;
  v_reason text := left(btrim(coalesce(p_reason, '')), 200);
  v_request_id uuid := coalesce(p_request_id, gen_random_uuid());
  v_attempt public.delivery_attempts%ROWTYPE;
  v_event jsonb;
  v_resolution text;
  v_previous_delivery_date date;
BEGIN
  IF v_user_id IS NULL THEN RAISE EXCEPTION 'must be signed in'; END IF;
  SELECT role, is_active,
    coalesce(nullif(btrim(full_name), ''), nullif(btrim(username), ''), 'Staff')
  INTO v_role, v_active, v_actor_name
  FROM public.profiles WHERE id = v_user_id;
  IF NOT coalesce(v_active, false)
     OR coalesce(v_role, '') NOT IN ('owner', 'manager', 'florist', 'delivery') THEN
    RAISE EXCEPTION 'role cannot record delivery outcomes';
  END IF;
  IF v_reason = '' THEN RAISE EXCEPTION 'delivery reason is required'; END IF;

  SELECT * INTO v_order FROM public.orders WHERE id = p_order_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'order not found'; END IF;
  SELECT * INTO v_attempt FROM public.delivery_attempts WHERE request_id = v_request_id;
  IF FOUND THEN
    IF v_attempt.order_id <> p_order_id OR v_attempt.attempted_by <> v_user_id THEN
      RAISE EXCEPTION 'delivery attempt request id is already used';
    END IF;
    RETURN jsonb_build_object('order_id', p_order_id, 'attempt_id', v_attempt.id,
      'resolution', v_attempt.resolution, 'already_recorded', true);
  END IF;
  IF v_order.deleted_at IS NOT NULL THEN RAISE EXCEPTION 'archived orders cannot be updated'; END IF;
  IF v_order.status IN ('done', 'cancelled') THEN
    RAISE EXCEPTION 'completed or cancelled orders cannot be updated';
  END IF;
  IF coalesce(v_order.status, '') NOT IN ('new', 'processing', 'ready') THEN
    RAISE EXCEPTION 'order has no valid status for a delivery outcome';
  END IF;
  IF p_new_date IS NOT NULL THEN
    IF v_order.delivery_method = 'pickup' THEN RAISE EXCEPTION 'pickup orders do not have a delivery date'; END IF;
    IF p_new_date <= (now() AT TIME ZONE 'Africa/Algiers')::date THEN
      RAISE EXCEPTION 'new delivery date must be in the future';
    END IF;
    IF v_order.delivery_date IS NOT NULL AND p_new_date <= v_order.delivery_date THEN
      RAISE EXCEPTION 'new delivery date must be later than the current date';
    END IF;
  END IF;

  v_resolution := CASE WHEN p_new_date IS NULL THEN 'returned_to_shop' ELSE 'rescheduled' END;
  v_previous_delivery_date := v_order.delivery_date;
  IF p_new_date IS NOT NULL THEN
    v_event := jsonb_build_object(
      'delayed_at', now(), 'delayed_by', v_user_id,
      'from_date', v_order.delivery_date, 'to_date', p_new_date,
      'reason', v_reason, 'source', 'failed_delivery'
    );
  END IF;

  v_old_order := to_jsonb(v_order);
  -- Insert first so notification handling can collapse the related order
  -- status/date event into this single attempt alert in the same transaction.
  INSERT INTO public.delivery_attempts (
    request_id, order_id, order_number, reason, resolution,
    attempted_by, actor_name, previous_delivery_date, rescheduled_delivery_date
  ) VALUES (
    v_request_id, p_order_id, v_order.order_number::text, v_reason, v_resolution,
    v_user_id, v_actor_name, v_previous_delivery_date, p_new_date
  ) RETURNING * INTO v_attempt;

  UPDATE public.orders SET
    status = 'processing',
    delivery_date = coalesce(p_new_date, delivery_date),
    original_delivery_date = CASE WHEN p_new_date IS NULL
      THEN original_delivery_date ELSE coalesce(original_delivery_date, delivery_date) END,
    delay_reason = CASE WHEN p_new_date IS NULL THEN delay_reason ELSE v_reason END,
    delayed_at = CASE WHEN p_new_date IS NULL THEN delayed_at ELSE now() END,
    delay_history = CASE WHEN p_new_date IS NULL THEN delay_history
      ELSE coalesce(delay_history, '[]'::jsonb) || jsonb_build_array(v_event) END,
    delivery_handed_off_at = NULL,
    delivery_handed_off_by = NULL
  WHERE id = p_order_id
  RETURNING * INTO v_order;

  INSERT INTO public.audit_logs (performed_by, action_taken, target_table, old_value, new_value)
  VALUES (v_user_id::text, 'delivery_outcome', 'orders', v_old_order, to_jsonb(v_order));

  RETURN jsonb_build_object('order_id', p_order_id, 'attempt_id', v_attempt.id,
    'resolution', v_attempt.resolution, 'already_recorded', false);
END;
$$;

REVOKE ALL ON FUNCTION public.record_delivery_outcome(uuid, text, text, date, uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.record_delivery_outcome(uuid, text, text, date, uuid) TO authenticated;
